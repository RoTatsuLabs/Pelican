#!/bin/sh
# Rebuilds shaders_spv.h from the GLSL files in shaders/. Needs glslangValidator (Khronos glslang).
# The header is checked in, so a normal build does not need this.
set -e
cd "$(dirname "$0")/shaders"
out=../shaders_spv.h
{
  echo "// Generated by compile_shaders.sh from shaders/*.vert and shaders/*.frag. Do not edit."
  echo "#pragma once"
  echo "#include <cstdint>"
  for s in mesh.vert mesh.frag quad.vert quad.frag; do
    glslangValidator -V "$s" -o "$s.spv" > /dev/null
    name=$(echo "$s" | awk -F. '{print "k" toupper(substr($1,1,1)) substr($1,2) toupper(substr($2,1,1)) substr($2,2)}')
    echo "static const uint32_t ${name}Spv[] = {"
    od -An -v -tx4 -w16 "$s.spv" | sed 's/ \([0-9a-f]\{8\}\)/0x\1,/g; s/^/    /'
    echo "};"
  done
} > "$out"
rm -f ./*.spv
